/* resolve a media entity's device node via media-ctl; falls back to
 * the observed post-reboot numbering on parse failure */
static int find_subdev_node(const char *entity, char *out, size_t outsz)
{
    char cmd[256];
    char buf[64];

    snprintf(cmd, sizeof cmd,
             "media-ctl -d /dev/media0 -p 2>/dev/null"
             " | grep -A4 '\"%s\"'"
             " | grep -o '/dev/v4l-subdev[0-9]*'"
             " | head -1", entity);
    FILE *f = popen(cmd, "r");
    if (f)
    {
        if (fgets(buf, sizeof buf, f) &&
            strncmp(buf, "/dev/v4l-subdev", 15) == 0)
        {
            buf[strcspn(buf, "\n")] = 0;
            snprintf(out, outsz, "%s", buf);
            pclose(f);
            return 0;
        }
        pclose(f);
    }
    return -1;
}

/* fire the recorded ISP parameter table at the isp.0 / h3a.0
 * subdevices; tolerant of individual failures */
int isp_replay_apply(void)
{
    char isp_node[32] = "/dev/v4l-subdev14";
    char h3a_node[32] = "/dev/v4l-subdev15";
    int fd_i, fd_h, fails = 0;
    unsigned i;

    find_subdev_node("sunxi_isp.0", isp_node, sizeof isp_node);
    find_subdev_node("sunxi_h3a.0", h3a_node, sizeof h3a_node);

    if (g_fd_isp >= 0)
        close(g_fd_isp);
    if (g_fd_h3a >= 0)
        close(g_fd_h3a);
    g_fd_isp = g_fd_h3a = -1;

    fd_i = open(isp_node, O_RDWR);
    fd_h = open(h3a_node, O_RDWR);
    if (fd_i < 0 || fd_h < 0)
        return -1;
    /* keep both open for the streaming session: the frame-done events
     * must be fetched through these handles (isp_events_fetch) */
    g_fd_isp = fd_i;
    g_fd_h3a = fd_h;

    for (i = 0; i < ISP_REPLAY_ISP_N; i++)
    {
        const isp_rec_t *r = &ISP_REPLAY_ISP[i];
        if (ioctl(fd_i, r->req, (void *)r->data) < 0)
            fails++;
    }
    for (i = 0; i < ISP_REPLAY_H3A_N; i++)
    {
        const isp_rec_t *r = &ISP_REPLAY_H3A[i];
        if (ioctl(fd_h, r->req, (void *)r->data) < 0)
            fails++;
    }

    return fails == ISP_REPLAY_ISP_N + ISP_REPLAY_H3A_N ? -1 : 0;
}

/* Fetch pending ISP events (0x80885659 on isp.0 + h3a.0). The BSP
 * delivers frame-done as an ISP event: poll() flags the video node
 * readable when an event is pending, but the buffer only completes
 * once the event is consumed. AWISPdemo calls this every iteration. */
int isp_events_fetch(void)
{
    unsigned char ev[136];
    int fails = 0;

    if (g_fd_isp >= 0 && ioctl(g_fd_isp, 0x80885659u, ev) < 0)
        fails++;
    if (g_fd_h3a >= 0 && ioctl(g_fd_h3a, 0x80885659u, ev) < 0)
        fails++;
    return fails == 2 ? -1 : 0;
}
